class RefreshToken(Base):
    """
    Stores refresh-token sessions.

    The JWT itself is not stored. The token_id corresponds to the JWT jti
    claim and allows individual sessions to be revoked.
    """

    __tablename__ = "refresh_tokens"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        default=uuid.uuid4,
    )

    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey(
            "users.id",
            ondelete="CASCADE",
        ),
        index=True,
        nullable=False,
    )

    token_id: Mapped[str] = mapped_column(
        String(64),
        unique=True,
        index=True,
        nullable=False,
    )

    # Browser, application, or client information.
    user_agent: Mapped[str | None] = mapped_column(
        String(500),
        nullable=True,
    )

    # Source IP address associated with the login session.
    ip_address: Mapped[str | None] = mapped_column(
        String(64),
        nullable=True,
    )

    expires_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )

    revoked_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )


class AuditEvent(Base):
    """
    Records important auth and security events.

    Examples:

    - USER_REGISTERED
    - EMAIL_VERIFIED
    - LOGIN_SUCCEEDED
    - LOGIN_FAILED
    - ACCOUNT_LOCKED
    - PASSWORD_RESET_REQUESTED
    - PASSWORD_RESET_COMPLETED
    - PASSWORD_CHANGED
    - SESSION_REVOKED
    - LOGOUT
    """

    __tablename__ = "audit_events"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        default=uuid.uuid4,
    )

    # Nullable because an audit record may remain after a user is deleted.
    user_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey(
            "users.id",
            ondelete="SET NULL",
        ),
        index=True,
        nullable=True,
    )

    event_type: Mapped[str] = mapped_column(
        String(100),
        index=True,
        nullable=False,
    )

    ip_address: Mapped[str | None] = mapped_column(
        String(64),
        nullable=True,
    )

    user_agent: Mapped[str | None] = mapped_column(
        String(500),
        nullable=True,
    )

    # Additional event-specific information.
    #
    # Examples:
    # {"role": "BUYER"}
    # {"attempt": 3}
    # {"session_id": "..."}
    details: Mapped[dict | None] = mapped_column(
        JSON,
        nullable=True,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )